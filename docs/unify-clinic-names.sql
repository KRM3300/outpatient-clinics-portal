-- توحيد أسماء العيادات في السجلات القديمة على قائمة الخدمات الإلكترونية (2026-11-16)
-- الأسماء التي ليس لها مقابل واضح تبقى كما هي: «العيادات الخارجية» و«اضطرابات النمو والسلوك» في البلاغات.

update public.opd_pe_cases set department = case department
    when 'الباطنية' then 'الباطنة'
    when 'الجراحة العامة' then 'الجراحة'
    when 'المخ والأعصاب' then 'طب المخ والأعصاب العامة'
    when 'الاعصاب' then 'طب المخ والأعصاب العامة'
  end
where department in ('الباطنية', 'الجراحة العامة', 'المخ والأعصاب', 'الاعصاب');

update public.opd_nc_reports set specialty = case
    when specialty = 'آخرى' then 'أخرى'
    when specialty in ('الأطفال', 'الأطفال ( الطفل السليم') then 'الأطفال ( الطفل السليم - حديثي الولادة )'
  end
where specialty in ('آخرى', 'الأطفال', 'الأطفال ( الطفل السليم');
